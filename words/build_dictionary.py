#!/usr/bin/env python3
"""Encode the word lists into a PROGMEM blob for AVR.

Layout
------
The guess set is sorted and split into 676 buckets by its first two letters.
The bucket is implied by the table slot, so those 10 bits are free. Inside a
bucket only the 3-letter suffix is coded, as gaps between consecutive suffixes,
Rice-coded with a per-bucket parameter k. Each bucket starts on a byte
boundary so the offset table stays 16-bit.

The answer set is a subset of the guess set, so it costs one bit per guess
word rather than storing any letters twice.
"""
import argparse
import re
from pathlib import Path
from collections import defaultdict
from build_answers import build_answers

ROOT = Path(__file__).resolve().parent.parent
L, OUT = ROOT / "words", ROOT / "src" / "wordset"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="fail if generated data is stale")
args = parser.parse_args()
try:
    build_answers(check=args.check)
except ValueError as error:
    parser.exit(1, f"{error}\n")


def load_words(path):
    words = path.read_text(encoding="utf-8").splitlines()
    if not words or any(not re.fullmatch(r"[a-z]{5}", w) for w in words):
        raise SystemExit(f"{path}: expected lowercase five-letter words, one per line")
    if words != sorted(set(words)):
        raise SystemExit(f"{path}: words must be sorted and unique")
    return words


answers = set(load_words(L / "answers.txt"))
if any(len(set(w)) != 5 for w in answers):
    raise SystemExit("answers must have five distinct letters for the physical tiles")
# Every selected target must also be an accepted guess.
guesses = sorted(set(load_words(L / "guesses.txt")) | answers)
N, NA = len(guesses), len(answers)
if N >= 65535:
    raise SystemExit("word count exceeds the decoder's 16-bit index capacity")

SUF = 26 ** 3
def suffix(w):
    v = 0
    for ch in w[2:]: v = v*26 + (ord(ch)-97)
    return v
def pre_id(w): return (ord(w[0])-97)*26 + (ord(w[1])-97)

buckets = defaultdict(list)
for w in guesses: buckets[pre_id(w)].append(suffix(w))
for v in buckets.values(): v.sort()

class BitWriter:
    def __init__(self): self.buf = bytearray(); self.acc = 0; self.n = 0
    def put(self, value, width):
        for i in range(width-1, -1, -1): self.bit((value >> i) & 1)
    def bit(self, b):
        self.acc = (self.acc << 1) | b; self.n += 1
        if self.n == 8: self.buf.append(self.acc); self.acc = 0; self.n = 0
    def rice(self, v, k):
        q = v >> k
        for _ in range(q): self.bit(1)
        self.bit(0)
        self.put(v & ((1 << k)-1), k)
    def align(self):
        while self.n: self.bit(0)

def gaps(vs):
    out, prev = [], -1
    for v in vs: out.append(v-prev-1); prev = v
    return out
def rice_cost(g, k): return sum((d >> k)+1+k for d in g)

bw = BitWriter()
offsets, counts, ks = [], [], []
for p in range(676):
    bw.align()
    offsets.append(len(bw.buf))
    vs = buckets.get(p, [])
    counts.append(len(vs))
    if not vs:
        ks.append(0); continue
    g = gaps(vs)
    k = min(range(1, 15), key=lambda kk: rice_cost(g, kk))
    ks.append(k)
    for d in g: bw.rice(d, k)
bw.align()
bw.buf.append(0)  # pad so the bit reader may always fetch one byte ahead
stream = bytes(bw.buf)

if max(counts) >= 256:
    raise SystemExit(f"bucket too large for a uint8 count: {max(counts)}")
if len(stream) >= 65536:
    raise SystemExit("stream exceeds 16-bit offsets")

k_packed = bytearray()
for i in range(0, 676, 2):
    k_packed.append((ks[i] << 4) | ks[i+1])

ans_bits = bytearray((N + 7) // 8)
for i, w in enumerate(guesses):
    if w in answers: ans_bits[i >> 3] |= 0x80 >> (i & 7)

sizes = {
    "Rice stream":        len(stream),
    "bucket offsets":     676 * 2,
    "bucket counts":      676,
    "bucket k (4-bit)":   len(k_packed),
    "answer bitmap":      len(ans_bits),
}
total = sum(sizes.values())
print(f"{N:,} guess words, {NA:,} answer words\n")
for k_, v in sizes.items(): print(f"  {k_:20s} {v:7,d} B")
print(f"  {'TOTAL':20s} {total:7,d} B   "
      f"({total*8/N:.2f} bits per guess word)")
print(f"\n  five-byte guess strings alone would be {N*5:,} B "
      f"-> {100*(1-total/(N*5)):.1f}% smaller, including answer selection")

def carr(name, data, typ="uint8_t"):
    body = ",".join(str(b) for b in data)
    wrapped, line = [], ""
    for tok in body.split(","):
        if len(line) + len(tok) + 1 > 92: wrapped.append(line); line = ""
        line += tok + ","
    wrapped.append(line.rstrip(","))
    return (f"const {typ} {name}[{len(data)}] PROGMEM = {{\n  "
            + "\n  ".join(wrapped) + "\n};\n")

hdr = f"""// Generated by words/build_dictionary.py -- do not edit.
//
// {N:,} valid 5-letter guess words, of which {NA:,} are answer words
// (Wikipedia-frequency targets, filtered for the physical tiles). Total {total:,} bytes of flash.
// Dictionary data attribution and licence: words/NOTICE.txt.
#pragma once
#include <stdint.h>
#ifdef ARDUINO
#include <avr/pgmspace.h>
#else
#define PROGMEM
#define pgm_read_byte(a) (*(const uint8_t *)(a))
#define pgm_read_word(a) (*(const uint16_t *)(a))
#endif

#define WORDSET_GUESS_COUNT  {N}
#define WORDSET_ANSWER_COUNT {NA}
#define WORDSET_FLASH_BYTES  {total}

namespace wordset_data {{

{carr("kStream", stream)}
{carr("kBucketOffset", offsets, "uint16_t")}
{carr("kBucketCount", counts)}
{carr("kBucketK", k_packed)}
{carr("kAnswerBits", ans_bits)}
}}  // namespace wordset_data
"""
target = OUT / "wordset_data.h"
if args.check:
    if not target.exists() or target.read_text() != hdr:
        raise SystemExit("wordset_data.h is stale; run python3 words/build_dictionary.py")
else:
    OUT.mkdir(parents=True, exist_ok=True)
    target.write_text(hdr)
print(f"\n{'verified' if args.check else 'wrote'} {target}")
